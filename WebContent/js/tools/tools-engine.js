// функции: одну — регистрирующую обработчики, вторую — возвращающую
// массив описаний. Так новый набор инструментов появляется отдельным
// файлом, без правки ядра и без разрастания _builtinDefs().
ToolsEngine.HANDLER_CONTRIBUTORS = [];
ToolsEngine.DEF_CONTRIBUTORS = [];

// ============================================================
//  TOOLS ENGINE — ядро: класс, состав модулей, точки расширения
// ============================================================
//
// Файл объявляет класс ToolsEngine и обязан подключаться ПЕРВЫМ:
// остальные tools-*.js дополняют ToolsEngine.prototype примесями —
// тот же приём, что уже применён в ui-*.js.
//
// Состав модулей:
//   tools-engine.js     — этот файл: класс, конструктор, точки расширения
//   tools-registry.js   — реестр обработчиков, загрузка, выдача tools в API
//   tools-executor.js   — исполнение инструмента, таймаут, шлюз безопасности
//   tools-builtin.js    — обработчики встроенных инструментов и их хелперы
//   tools-defs.js       — описания (JSON Schema) встроенных инструментов
//   tools-mcp.js        — клиент MCP и политики доступа к MCP-серверам
//   tools-llm-router.js — инструменты управления подключениями к LLM
//
// ЗАЧЕМ РАЗБИВКА. Файл вырос до ~2500 строк, где описания инструментов,
// их обработчики, исполнение и проверки лежали вперемешку: правка одного
// инструмента заставляла листать весь файл. Границы проведены по РОЛИ
// кода (что описывает / что исполняет / что охраняет), а не по предметным
// группам инструментов — предметная группировка развалилась бы на первом
// же инструменте, который относится сразу и к файлам, и к папкам.

class ToolsEngine {
  constructor(db) {
    this.db = db;
    this.ui = null;            // ← ссылка на UI устанавливается извне
    this.folders = null;       // ← ссылка на FoldersEngine устанавливается извне (см. agent.js)
    this.files = null;         // ← ссылка на FilesEngine устанавливается извне (см. agent.js)
    this.security = null;      // ← ссылка на SecurityEngine устанавливается извне
    this.registry = new Map();
    // Подробное логирование каждого tool-вызова (аргументы, результат) в
    // консоль. По умолчанию выключено — раньше писалось безусловно и могло
    // содержать чувствительные данные из аргументов/результатов инструментов.
    // Включить для отладки: agent.tools.debug = true (в DevTools console).
    this.debug = false;
    // Реестр провайдеров и моделей (LLMRegistry). Нужен инструментам
    // выбора модели из tools-llm-router.js. Ставится из agent.js.
    this.llmRegistry = null;

    this._initBuiltinTools();
    // Модули, подключённые после ядра, добавляют свои обработчики здесь.
    // Прямой вызов из _initBuiltinTools невозможен: примеси к прототипу
    // применяются позже, при загрузке следующих файлов, тогда как сам
    // конструктор выполняется уже после загрузки всех скриптов.
    for (const contribute of ToolsEngine.HANDLER_CONTRIBUTORS) {
      try { contribute.call(this); }
      catch (e) { console.error('ToolsEngine: сбой регистрации обработчиков модуля', e); }
    }
  }
}


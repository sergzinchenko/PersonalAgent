// ============================================================
//  TOOLS BACKUP — резервная копия агента по просьбе в разговоре
// ============================================================
//
// Просьба «сделай резервную копию» или «перенеси себя на другой
// компьютер» произносится в чате, а не в окне настроек, — и агент должен
// уметь её исполнить, а не пересказывать путь в меню.
//
// ИНСТРУМЕНТ ОТКРЫВАЕТ ФОРМУ, А НЕ ДЕЛАЕТ РАБОТУ САМ — по той же причине,
// что и *_configure у вики (см. tools-wiki.js): копия шифруется паролем,
// а пароль, собранный через ask_user, стал бы результатом вызова
// инструмента, то есть частью истории диалога, которая уходит провайдеру
// при каждом следующем запросе. Агент здесь инициирует действие, но ни
// пароля, ни содержимого копии не видит.
//
// Состав и подсказки берутся из BackupEngine.PARTS — тех же, что
// показывает форма: агент должен рассказывать про то, что человек
// реально увидит на экране, а не про отдельно написанный список.

ToolsEngine.HANDLER_CONTRIBUTORS.push(function registerBackupHandlers() {

  this.registerHandler('builtin_backup', async (params) => {
    const ui = this.ui;
    const p = params || {};
    const action = String(p.action || 'export').toLowerCase();

    if (action === 'parts') {
      return {
        parts: BackupEngine.PARTS.map(s => ({
          id: s.id,
          label: s.label,
          contains_credentials: !!s.secrets,
          description: s.hint,
        })),
        note: 'Пользователь отмечает нужные части сам в форме. Перечисли их своими словами, ' +
              'если он спрашивает, что попадёт в копию.',
      };
    }

    if (action === 'export') {
      if (!ui || typeof ui.showBackupExportModal !== 'function') {
        return { error: 'Форма резервной копии недоступна (интерфейс не подключён)' };
      }
      ui.showBackupExportModal();
      return {
        opened: true,
        note: 'Открыта форма выгрузки: пользователь отмечает состав, задаёт пароль и скачивает файл. ' +
              'Пароль задаёт он сам — не спрашивай его в переписке и не предлагай свой. ' +
              'Содержимое копии тебе не передаётся.',
      };
    }

    if (action === 'restore') {
      if (!ui || typeof ui.showBackupImportModal !== 'function') {
        return { error: 'Форма восстановления недоступна (интерфейс не подключён)' };
      }
      // Промис формы не ждём: восстановление заканчивается перезагрузкой
      // страницы, и ход, который его дождался бы, оборвался бы вместе с
      // вкладкой — попав при этом в список прерванных.
      ui.showBackupImportModal({ firstRun: false });
      return {
        opened: true,
        note: 'Открыта форма восстановления: пользователь выбирает файл, вводит пароль и отмечает, ' +
              'что вернуть. После восстановления страница перезагрузится — это нормально, ' +
              'так подхватываются вернувшиеся настройки.',
      };
    }

    return { error: `Неизвестное действие "${action}". Доступны: export, restore, parts.` };
  });

});


ToolsEngine.DEF_CONTRIBUTORS.push(function backupDefs() {
  return [
    {
      id: 'builtin_backup',
      name: 'backup',
      description:
        'Резервная копия агента целиком: имя, настройки, подключения к моделям, инструменты, ' +
        'навыки, промпты, память и переписка — одним зашифрованным файлом.\n' +
        'action=export — открыть форму выгрузки (пользователь отметит состав и задаст пароль); ' +
        'action=restore — открыть форму восстановления из файла; ' +
        'action=parts — перечень того, из чего состоит копия (ответить на вопрос «что туда попадёт»).\n' +
        'Вызывай на просьбы «сделай резервную копию», «сохрани настройки в файл», ' +
        '«перенеси себя на другой компьютер», «восстанови из копии».\n' +
        'Пароль задаёт пользователь в форме: не спрашивай его в переписке и не придумывай сам.',
      parameters: {
        type: 'object',
        properties: {
          action: {
            type: 'string',
            enum: ['export', 'restore', 'parts'],
            description: 'Что сделать. По умолчанию export.',
          },
        },
        required: [],
      },
      enabled: true,
      builtin: true,
      // Системный: выключить нельзя (см. навык «Системный»).
      locked: true,
    },
  ];
});

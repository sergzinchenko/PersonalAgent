// ============================================================
//  TOOLS SUBTASK — решение задачи по частям
// ============================================================
//
// Инструмент run_subtask: часть работы выполняется отдельным ходом в
// отдельном чате, а в основную переписку возвращается только итог.
// Механика — в ui/ui-subtask.js, здесь описание и связка с интерфейсом
// (цикл подзадачи живёт в UI, потому что ему нужны те же настройки,
// статус в чате и реакция на кнопку останова, что и обычному ходу).
//
// Инструмент СИСТЕМНЫЙ (locked): экономия контекста не должна зависеть
// от того, вспомнил ли пользователь включить тумблер, — а выключенный
// инструмент модели не передаётся вовсе.

ToolsEngine.HANDLER_CONTRIBUTORS.push(function registerSubtaskHandlers() {

  this.registerHandler('builtin_run_subtask', async (params) => {
    const ui = this.ui;
    if (!ui || typeof ui.runSubtask !== 'function') {
      return { error: 'Подзадачи недоступны: интерфейс не подключён' };
    }
    // Родитель — чат, который сейчас ведёт ход. Инструменты вызываются
    // только из активного хода, а он ровно один на приложение.
    const parentChatId = ui._chatRuns.size
      ? ui._chatRuns.keys().next().value
      : ui.currentChatId;
    if (!parentChatId) return { error: 'Нет активного чата для подзадачи' };

    return ui.runSubtask(parentChatId, params || {});
  });

});


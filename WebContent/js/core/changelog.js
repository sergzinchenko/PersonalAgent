// Неизвестная категория не должна ломать показ: старая запись без неё
// или новая с опечаткой просто попадёт в «Прочее».
const APP_RELEASE_CATEGORY_OTHER = { id: 'other', icon: '•', label: 'Прочее', hint: '' };

function releaseCategory(id) {
  return APP_RELEASE_CATEGORIES.find(c => c.id === id) || APP_RELEASE_CATEGORY_OTHER;
}

// Пункты релиза в едином виде { cat, text }. Строка, оставшаяся от старой
// записи (или пришедшая из чужого архива), превращается в пункт «Прочее»:
// перечень возможностей важнее, чем его раскладка.
function releaseItems(release) {
  return ((release && release.items) || []).map((item) => (
    typeof item === 'string'
      ? { cat: 'other', text: item }
      : { cat: item && item.cat ? item.cat : 'other', text: (item && item.text) || '' }
  ));
}

// Сколько пунктов в каждой категории — для подписей на фильтре. Порядок
// тот же, что у APP_RELEASE_CATEGORIES; пустые категории не возвращаются.
function releaseCategoryCounts(releases) {
  const counts = new Map();
  for (const r of releases || []) {
    for (const it of releaseItems(r)) counts.set(it.cat, (counts.get(it.cat) || 0) + 1);
  }
  const out = APP_RELEASE_CATEGORIES.filter(c => counts.has(c.id))
    .map(c => ({ ...c, count: counts.get(c.id) }));
  if (counts.has('other')) out.push({ ...APP_RELEASE_CATEGORY_OTHER, count: counts.get('other') });
  return out;
}


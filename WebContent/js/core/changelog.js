// Последний релиз: им отмечается «прочитано» при первом запуске.
function latestRelease() {
  return APP_RELEASES[APP_RELEASES.length - 1] || null;
}

// Релизы новее указанного номера, от старых к новым: ровно то, чего
// пользователь ещё не видел.
function releasesSince(n) {
  const from = Number(n) || 0;
  return APP_RELEASES.filter(r => r.n > from);
}

function releaseByNumber(n) {
  return APP_RELEASES.find(r => r.n === Number(n)) || null;
}

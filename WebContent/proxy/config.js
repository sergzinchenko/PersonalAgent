// Конфигурация локального прокси. Лежит рядом с proxy.js — правьте значения
// и просто перезапустите proxy.js, никаких переменных окружения не нужно.
module.exports = {
  // Порт, на котором прокси слушает входящие запросы из браузера.
  port: 3000,

  // Разрешённые HTTP-методы. GET/HEAD тела не имеют, остальные поддерживаются полностью.
  allowedMethods: ['GET', 'POST', 'PUT', 'DELETE', 'PATCH', 'HEAD'],

  // Белый список хостов, куда прокси разрешено ходить (защита от SSRF —
  // без него любая страница, знающая порт прокси, может ходить куда угодно
  // от имени вашей локальной машины). Пустой массив = ограничений нет,
  // подходит только для локальной разработки.
  allowlist: [],

  // Максимальный размер тела входящего запроса от браузера, в байтах.
  maxRequestBodyBytes: 10 * 1024 * 1024, // 10 MB

  // Сколько байт тела запроса/ответа печатать в консоль при логировании
  // (пересылка клиенту при этом всегда идёт полностью, лимит только для лога).
  maxLogBytes: 4096,

  // Отключить цветной (ANSI) вывод в консоли — удобно, если логи пишутся в файл.
  noColor: false,

  // ---- TLS: доверие к сертификатам целевых серверов ----
  // Внутренние (корпоративные) серверы обычно выпускают сертификаты своим
  // удостоверяющим центром, которого нет в списке доверенных у Node. Без
  // настройки такой запрос падает, и прокси отвечает 502.
  //
  // Варианты перечислены от правильного к крайнему — берите первый, который
  // применим.
  tls: {
    // 1. ЛУЧШИЙ ВАРИАНТ. Путь к PEM-файлу с сертификатом вашего
    //    удостоверяющего центра (можно несколько, склеенных подряд).
    //    Проверка при этом ОСТАЁТСЯ включённой: подменённый сертификат
    //    по-прежнему будет отвергнут, просто теперь Node знает ваш CA.
    //    Путь абсолютный или относительно папки с proxy.js.
    caFile: '',

    // 2. КОМПРОМИСС. Не проверять сертификаты только у этих хостов.
    //    'corp.local' покрывает и 'intranet.corp.local'. Годится, когда
    //    до CA-файла не добраться, а ходить нужно на один-два адреса.
    insecureHosts: [],

    // 3. КРАЙНИЙ СЛУЧАЙ. Не проверять сертификаты вообще ни у кого.
    //    Это отключает защиту от подмены сервера на ВСЕХ адресах, включая
    //    внешние: перехватчик трафика станет неотличим от настоящего
    //    сервера. Держите включённым только на время разбирательства.
    insecure: false,
  },

  // ---- SSO: аутентификация к целевому серверу через curl (NTLM/Negotiate) ----
  // Включается на конкретный запрос заголовком X-Use-Sso: 1 или query-параметром
  // ?sso=1 — остальные запросы всегда идут обычным путём через http/https.
  sso: {
    // Путь к исполняемому файлу curl. По умолчанию берётся из PATH:
    // curl.exe на Windows (с июля 2024 идёт в системе со встроенной поддержкой
    // SSPI), curl на прочих ОС. Укажите полный путь, если curl не на PATH.
    curlBin: process.platform === 'win32' ? 'curl.exe' : 'curl',

    // Какие механизмы аутентификации разрешить curl использовать.
    // На Windows с пустыми user:pass (см. runCurlRequest) это включает SSO
    // текущего залогиненного пользователя через SSPI, без ввода пароля.
    useNtlm: true,
    useNegotiate: true,

    // -k / --insecure у curl — принимать самоподписанные сертификаты
    // (частая ситуация с внутренними корпоративными серверами).
    insecure: false,

    // Таймаут одного запроса curl, в секундах.
    timeoutSec: 60,

    // Максимальный размер ответа цели в SSO-режиме, в байтах — в этом режиме
    // ответ curl буферизуется в памяти целиком, поэтому лимит важен.
    maxResponseBytes: 20 * 1024 * 1024, // 20 MB
  },
};